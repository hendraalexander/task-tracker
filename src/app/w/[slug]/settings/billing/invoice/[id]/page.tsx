import { notFound } from "next/navigation";
import Link from "next/link";
import { prisma } from "@/lib/db";
import { requireWorkspaceAdmin } from "@/lib/access";
import { formatDate } from "@/lib/format";
import { normalizeLocale } from "@/lib/i18n";
import { PrintButton } from "@/components/settings/print-button";
import { Card } from "@/components/ui/primitives";
import { BrandLogo } from "@/components/brand/logo";

export default async function InvoicePage({
  params,
}: {
  params: Promise<{ slug: string; id: string }>;
}) {
  const { slug, id } = await params;
  const ctx = await requireWorkspaceAdmin(slug);
  const invoice = await prisma.invoice.findFirst({ where: { id, workspaceId: ctx.workspace.id } });
  if (!invoice) notFound();

  const locale = normalizeLocale(ctx.user.locale);

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between">
        <Link href={`/w/${slug}/settings/billing`} className="text-[12px] font-medium text-muted-foreground hover:text-foreground">
          ← Billing
        </Link>
        <PrintButton label={locale === "id" ? "Cetak / simpan PDF" : "Print / save PDF"} />
      </div>

      <Card className="mx-auto max-w-[720px] p-8 print:border-0 print:shadow-none">
        <div className="flex items-start justify-between border-b border-border pb-5">
          <div>
            <BrandLogo href="/" size={26} textClassName="text-[16px]" />
            <p className="mt-2 text-[11px] text-muted-foreground">atracker.app · billing@atracker.app</p>
          </div>
          <div className="text-right">
            <p className="text-[11px] font-semibold uppercase tracking-wider text-muted-foreground">{locale === "id" ? "Invoice" : "Invoice"}</p>
            <p className="text-[16px] font-bold">{invoice.number}</p>
            <p className="text-[11px] text-muted-foreground">{formatDate(invoice.createdAt, locale, ctx.user.timezone, ctx.user.dateFormat)}</p>
          </div>
        </div>

        <div className="grid gap-5 py-5 sm:grid-cols-2">
          <div>
            <p className="text-[10px] font-semibold uppercase tracking-wider text-muted-foreground">{locale === "id" ? "Ditagihkan kepada" : "Billed to"}</p>
            <p className="mt-1 text-[13px] font-semibold">{ctx.workspace.name}</p>
            <p className="text-[11.5px] text-muted-foreground">{ctx.user.email}</p>
          </div>
          <div>
            <p className="text-[10px] font-semibold uppercase tracking-wider text-muted-foreground">{locale === "id" ? "Periode" : "Period"}</p>
            <p className="mt-1 text-[12px]">
              {formatDate(invoice.periodStart, locale, ctx.user.timezone, ctx.user.dateFormat)} –{" "}
              {formatDate(invoice.periodEnd, locale, ctx.user.timezone, ctx.user.dateFormat)}
            </p>
            <p className="mt-2 text-[10px] font-semibold uppercase tracking-wider text-muted-foreground">Status</p>
            <p className="text-[12px] font-medium capitalize">{invoice.status}</p>
          </div>
        </div>

        <table className="w-full border-t border-border text-[12px]">
          <thead>
            <tr className="text-left text-[10px] uppercase tracking-wider text-muted-foreground">
              <th className="py-2 font-semibold">{locale === "id" ? "Deskripsi" : "Description"}</th>
              <th className="py-2 text-right font-semibold">{locale === "id" ? "Jumlah" : "Amount"}</th>
            </tr>
          </thead>
          <tbody>
            <tr className="border-t border-border/60">
              <td className="py-3">
                A Tracker {ctx.workspace.plan} · {locale === "id" ? "langganan per seat" : "per-seat subscription"}
              </td>
              <td className="py-3 text-right font-medium">${(invoice.amountCents / 100).toFixed(2)}</td>
            </tr>
          </tbody>
          <tfoot>
            <tr className="border-t border-border">
              <td className="py-3 text-right font-semibold">{locale === "id" ? "Total" : "Total"}</td>
              <td className="py-3 text-right text-[15px] font-bold">${(invoice.amountCents / 100).toFixed(2)}</td>
            </tr>
          </tfoot>
        </table>

        <p className="mt-6 border-t border-border pt-3 text-[10px] leading-relaxed text-muted-foreground">
          {locale === "id"
            ? "Dokumen ini dihasilkan oleh A Tracker dalam mode demo. Pembayaran diproses melalui Stripe pada lingkungan produksi."
            : "This document was generated by A Tracker in demo mode. Payments are processed by Stripe in production."}
        </p>
      </Card>
    </div>
  );
}
